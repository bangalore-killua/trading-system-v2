"""
signal_scientist.py — Pattern recognition, signal validation, backtesting agent.

Analyses the trading signals generated by LightGBM and YOLOv8,
validates their quality, and suggests improvements.
"""

from data.fincept.agents.base import BaseAgent

_SYSTEM = """You are a quantitative signal researcher at a systematic trading firm.
You have deep expertise in evaluating trading signals for statistical validity.

Your job is to:
1. Assess the quality of current signals (are they high conviction or marginal?)
2. Identify any patterns in false positives or missed trades
3. Suggest one concrete improvement to the model or signal generation

Output format — always produce exactly these sections:
## Signal Quality Assessment
[Table: symbol | signal | lgbm_score | groq_verdict | consensus | quality_rating (A/B/C/D)]

## Pattern Analysis
[2-3 sentences: what patterns do you see across today's signals?]

## False Positive Risk
[Which signals are most likely to fail and why — bullet list max 3]

## Improvement Suggestion
[One specific, actionable suggestion to improve signal quality]
"""


class SignalScientistAgent(BaseAgent):
    def __init__(self):
        super().__init__("SignalScientist", _SYSTEM)

    def _format_user_message(self, context: dict) -> str:
        signals = context.get("top_signals", [])
        conflict_count = context.get("conflict_count_30d", 0)
        recent_accuracy = context.get("recent_wf_accuracy", None)
        regime = context.get("regime", "UNKNOWN")

        s_lines = "\n".join(
            f"  {s['symbol']}: lgbm={s.get('lgbm_score', 0):.3f}, "
            f"groq={s.get('groq_verdict', '?')}, consensus={s.get('consensus', '?')}, "
            f"patterns={s.get('yolo_patterns', [])}"
            for s in signals[:15]
        ) or "  (no signals today)"

        return f"""Market regime: {regime}
Walk-forward accuracy (recent): {recent_accuracy if recent_accuracy else 'N/A'}
CONFLICT signals in last 30 days: {conflict_count}

Today's signals:
{s_lines}

Analyse signal quality and provide the structured report."""
