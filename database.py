# database.py
# v6.0 — PostgreSQL database layer
#
# Live on DigitalOcean: PostgreSQL 15 managed database,
# connection string via DATABASE_URL in .env
# Single source of truth for all persistent data.
# Replaces all JSON files in logs/ directory.
#
# Tables:
#   signals          — every score/signal generated (replaces latest_signals.json)
#   positions        — open position state machine (replaces open_positions.json)
#   trades           — completed trade history (replaces trade_state.json)
#   screener_results — weekly screener output (replaces screener_results.json)
#   equity_curve     — daily portfolio value (replaces equity_curve.json)
#   watchlist_history— tracks watchlist changes over time
#   score_history    — full scorecard per symbol per run
#   system_events    — errors, regime changes, alerts, audit trail
#
# Usage:
#   from database import get_db
#   db = get_db()
#   db.save_signal(symbol, scorecard)
#   db.get_latest_signals()

