    def get_latest_signals(self) -> list:
        """
        Returns the most recent signal for each symbol.
        Replaces reading latest_signals.json.
        """
        try:
            from sqlalchemy import func
            with get_session() as session:
                # subquery: MAX(created_at) per symbol
                subq = (
                    session.query(
                        Signal.symbol,
                        func.max(Signal.created_at).label("max_ts")
                    )
                    .group_by(Signal.symbol)
                    .subquery()
                )
                results = (
                    session.query(Signal)
                    .join(
                        subq,
                        (Signal.symbol == subq.c.symbol) &
                        (Signal.created_at == subq.c.max_ts)
                    )
                    .all()
                )
                return [self._signal_to_dict(r) for r in results]
        except Exception as e:
            log.error(f"get_latest_signals failed: {e}")
            # fallback — deduplicate in Python
            try:
                with get_session() as session:
                    seen    = set()
                    results = []
                    rows    = (
                        session.query(Signal)
                        .order_by(Signal.created_at.desc())
                        .limit(500)
                        .all()
                    )
                    for r in rows:
                        if r.symbol not in seen:
                            seen.add(r.symbol)
                            results.append(
                                self._signal_to_dict(r)
                            )
                    return results
            except Exception:
                return []

    def get_signal_history(self, symbol: str,
                            days: int = 30) -> list:
        """Returns signal history for a symbol."""
        try:
            cutoff = datetime.utcnow() - timedelta(days=days)
            with get_session() as session:
                results = (
                    session.query(Signal)
                    .filter(
                        Signal.symbol     == symbol,
                        Signal.created_at >= cutoff
                    )
                    .order_by(Signal.created_at.desc())
                    .all()
                )
                return [self._signal_to_dict(r)
                        for r in results]
        except Exception as e:
            log.error(
                f"get_signal_history failed for {symbol}: {e}"
            )
            return []

    # ── Positions ─────────────────────────────────────────────

    def save_position(self, position_data: dict) -> None:
        """Saves or updates an open position."""
        try:
            with get_session() as session:
                existing = (
                    session.query(Position)
                    .filter_by(
                        symbol=position_data["symbol"]
                    )
                    .first()
                )
                if existing:
                    # update existing
                    for k, v in position_data.items():
                        if hasattr(existing, k):
                            setattr(existing, k, v)
                    existing.updated_at = datetime.utcnow()
                else:
                    # create new
                    pos = Position(**{
                        k: v for k, v in position_data.items()
                        if hasattr(Position, k)
                    })
                    session.add(pos)
        except Exception as e:
            log.error(
                f"save_position failed for "
                f"{position_data.get('symbol')}: {e}"
            )

    def close_position_db(self, symbol: str) -> None:
        """Marks a position as closed."""
        try:
            with get_session() as session:
                pos = (
                    session.query(Position)
                    .filter_by(symbol=symbol, is_open=True)
                    .first()
                )
                if pos:
                    pos.is_open    = False
                    pos.updated_at = datetime.utcnow()
        except Exception as e:
            log.error(
                f"close_position_db failed for {symbol}: {e}"
            )

