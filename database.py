    def get_performance_summary(self) -> dict:
        """
        Returns portfolio performance summary.
        Used by performance analytics dashboard.
        """
        try:
            with get_session() as session:
                sells = (
                    session.query(Trade)
                    .filter_by(action="SELL")
                    .all()
                )

                if not sells:
                    return {
                        "total_trades":    0,
                        "win_rate":        0,
                        "total_pnl":       0,
                        "avg_pnl_pct":     0,
                        "best_trade":      0,
                        "worst_trade":     0,
                        "profit_factor":   0,
                    }

                wins   = [t for t in sells
                          if (t.pnl or 0) > 0]
                losses = [t for t in sells
                          if (t.pnl or 0) <= 0]

                total_pnl    = sum(
                    t.pnl or 0 for t in sells
                )
                gross_profit = sum(
                    t.pnl or 0 for t in wins
                ) if wins else 0
                gross_loss   = abs(sum(
                    t.pnl or 0 for t in losses
                )) if losses else 0

                return {
                    "total_trades":  len(sells),
                    "winning_trades": len(wins),
                    "losing_trades":  len(losses),
                    "win_rate": round(
                        len(wins) / len(sells) * 100, 2
                    ),
                    "total_pnl":  round(total_pnl, 2),
                    "avg_pnl_pct": round(
                        sum(t.pnl_pct or 0 for t in sells)
                        / len(sells), 2
                    ),
                    "best_trade":  round(
                        max(t.pnl_pct or 0 for t in sells), 2
                    ),
                    "worst_trade": round(
                        min(t.pnl_pct or 0 for t in sells), 2
                    ),
                    "profit_factor": round(
                        gross_profit / gross_loss, 3
                    ) if gross_loss > 0 else float("inf"),
                    "gross_profit": round(gross_profit, 2),
                    "gross_loss":   round(gross_loss, 2),
                }
        except Exception as e:
            log.error(f"get_performance_summary failed: {e}")
            return {}

    def get_bundle_performance(self) -> list:
        """Returns P&L breakdown by bundle."""
        try:
            with get_session() as session:
                sells = (
                    session.query(Trade)
                    .filter_by(action="SELL")
                    .all()
                )
                bundles = {}
                for t in sells:
                    b = t.bundle_id or "unknown"
                    if b not in bundles:
                        bundles[b] = {
                            "bundle_id": b,
                            "trades":    0,
                            "wins":      0,
                            "total_pnl": 0,
                        }
                    bundles[b]["trades"]    += 1
                    bundles[b]["total_pnl"] += t.pnl or 0
                    if (t.pnl or 0) > 0:
                        bundles[b]["wins"] += 1

                result = []
                for b, data in bundles.items():
                    n = data["trades"]
                    result.append({
                        **data,
                        "win_rate": round(
                            data["wins"] / n * 100, 2
                        ) if n > 0 else 0,
                        "avg_pnl":  round(
                            data["total_pnl"] / n, 2
                        ) if n > 0 else 0,
                    })
                return sorted(
                    result,
                    key=lambda x: -x["total_pnl"]
                )
        except Exception as e:
            log.error(f"get_bundle_performance failed: {e}")
            return []

