    def get_hygiene_candidates(self, days: int = 60,
                                min_scores: int = 20,
                                avg_score_threshold: float = 45.0
                                ) -> list:
        """
        V12-3: Returns symbols that meet ALL removal criteria:
          - Scored >= min_scores times in the last days days
          - Never triggered a BUY entry (triggered_entry=False)
          - Average normalised_score < avg_score_threshold
          - Not in open positions (checked by caller)
        """
        try:
            cutoff = datetime.utcnow() - timedelta(days=days)
            with get_session() as session:
                from sqlalchemy import func
                rows = (
                    session.query(
                        ScoreHistory.symbol,
                        func.count(ScoreHistory.id).label("score_count"),
                        func.avg(
                            ScoreHistory.normalised_score
                        ).label("avg_score"),
                        func.max(
                            ScoreHistory.normalised_score
                        ).label("max_score"),
                        func.bool_or(
                            ScoreHistory.triggered_entry
                        ).label("ever_entered"),
                    )
                    .filter(ScoreHistory.created_at >= cutoff)
                    .group_by(ScoreHistory.symbol)
                    .having(
                        func.count(ScoreHistory.id) >= min_scores,
                        func.avg(
                            ScoreHistory.normalised_score
                        ) < avg_score_threshold,
                        func.bool_or(
                            ScoreHistory.triggered_entry
                        ).is_(False),
                    )
                    .all()
                )
                return [
                    {
                        "symbol":      r.symbol,
                        "score_count": r.score_count,
                        "avg_score":   round(float(r.avg_score or 0), 1),
                        "max_score":   round(float(r.max_score or 0), 1),
                        "ever_entered": bool(r.ever_entered),
                    }
                    for r in rows
                ]
        except Exception as e:
            log.error(f"get_hygiene_candidates failed: {e}")
            return []


