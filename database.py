def get_connection_string() -> str:
    """Builds PostgreSQL connection string from .env."""
    host     = os.getenv("DB_HOST",     "localhost")
    port     = os.getenv("DB_PORT",     "5432")
    dbname   = os.getenv("DB_NAME",     "trading_system")
    user     = os.getenv("DB_USER",     "killua_trading")
    password = quote_plus(os.getenv("DB_PASSWORD", ""))
    return (
        f"postgresql://{user}:{password}"
        f"@{host}:{port}/{dbname}"
    )


_engine        = None
_SessionLocal  = None


def init_db() -> None:
    """
    Initialises database connection and creates all tables.
    Call once at application startup.
    """
    global _engine, _SessionLocal

    conn_str   = get_connection_string()
    _engine    = create_engine(
        conn_str,
        pool_size       = 5,
        max_overflow    = 10,
        pool_pre_ping   = True,   # verify connection before use
        pool_recycle    = 3600,   # recycle connections hourly
    )

    # create all tables if they don't exist
    Base.metadata.create_all(_engine)

    _SessionLocal = sessionmaker(
        bind=_engine, autocommit=False, autoflush=False
    )
    log.info("Database initialised successfully")


@contextmanager
def get_session():
    """
    Context manager for database sessions.
    Handles commit/rollback automatically.

    Usage:
        with get_session() as db:
            db.add(some_object)
    """
    if _SessionLocal is None:
        init_db()

    session = _SessionLocal()
    try:
        yield session
        session.commit()
    except SQLAlchemyError as e:
        session.rollback()
        log.error(f"Database error: {e}")
        raise
    finally:
        session.close()


