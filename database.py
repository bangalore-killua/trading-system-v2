    def migrate_from_json(self, logs_dir: str) -> dict:
        """
        Migrates existing JSON log files into PostgreSQL.
        Run once after database setup.
        Safe to run multiple times — skips existing data.

        Args:
            logs_dir: path to logs/ directory

        Returns:
            dict with migration counts
        """
        counts = {
            "signals":  0,
            "trades":   0,
            "positions": 0,
            "equity":   0,
            "errors":   [],
        }

        # migrate latest_signals.json
        signals_path = os.path.join(
            logs_dir, "latest_signals.json"
        )
        if os.path.exists(signals_path):
            try:
                with open(signals_path) as f:
                    signals = json.load(f)
                self.save_signals_batch(signals)
                counts["signals"] = len(signals)
                log.info(
                    f"  Migrated {len(signals)} signals"
                )
            except Exception as e:
                counts["errors"].append(
                    f"signals: {e}"
                )

        # migrate trade_state.json
        state_path = os.path.join(
            logs_dir, "trade_state.json"
        )
        if os.path.exists(state_path):
            try:
                with open(state_path) as f:
                    state = json.load(f)
                for symbol, trade in state.items():
                    # old format has different field names
                    # map to new Trade table fields
                    trade_data = {
                        "symbol":        symbol,
                        "action":        trade.get(
                            "last_action", "SELL"
                        ),
                        "price":         trade.get(
                            "last_price",
                            trade.get("price", 0)
                        ),
                        "entry_price":   trade.get(
                            "entry_price"
                        ),
                        "pnl_pct":       trade.get(
                            "pnl_pct"
                        ),
                        "cooldown_until": trade.get(
                            "cooldown_until"
                        ),
                        "trade_id":      trade.get(
                            "trade_id"
                        ),
                    }
                    self.save_trade(trade_data)
                    counts["trades"] += 1
                log.info(
                    f"  Migrated {counts['trades']} trades"
                )
            except Exception as e:
                counts["errors"].append(
                    f"trades: {e}"
                )

        # migrate open_positions.json
        pos_path = os.path.join(
            logs_dir, "open_positions.json"
        )
        if os.path.exists(pos_path):
            try:
                with open(pos_path) as f:
                    positions = json.load(f)
                for symbol, pos in positions.items():
                    self.save_position(pos)
                    counts["positions"] += 1
                log.info(
                    f"  Migrated {counts['positions']} "
                    f"positions"
                )
            except Exception as e:
                counts["errors"].append(
                    f"positions: {e}"
                )

        # migrate equity_curve.json
        equity_path = os.path.join(
            logs_dir, "equity_curve.json"
        )
        if os.path.exists(equity_path):
            try:
                with open(equity_path) as f:
                    curve = json.load(f)
                labels = curve.get("labels", [])
                values = curve.get("values", [])
                for date, value in zip(labels, values):
                    self.save_equity_point(date, value)
                    counts["equity"] += 1
                log.info(
                    f"  Migrated {counts['equity']} "
                    f"equity points"
                )
            except Exception as e:
                counts["errors"].append(
                    f"equity: {e}"
                )

        log.info(f"Migration complete: {counts}")
        return counts

